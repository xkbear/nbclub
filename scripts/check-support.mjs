import assert from 'node:assert/strict';
import {readFileSync,statSync,readdirSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const read=f=>readFileSync(join(root,f),'utf8');
const page='event-2026-11-15-nxt.html', assets='assets/events/2026-11-15-s01/';
const detail=read(page),home=read('index.html'),archive=read('events.html'),hub=read('support.html');
const schema=[...detail.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)].map(x=>JSON.parse(x[1]));
const event=schema.find(x=>x['@type']==='Event');
assert.equal(event.organizer.name,'NXT');
assert.equal(event.sponsor.name,'NewBee AI Club · 先蜂会');
assert.equal(event.startDate,'2026-11-14T11:00:00+13:00');
assert.equal(event.endDate,'2026-11-15T16:30:00+13:00');
assert(!event.offers&&!event.eventStatus);
for(const s of ['待发放','约 24','17','51','NZ$300','NZ$325','https://luma.com/xjt7e6tj',assets+'nxt-build-sprint-report.pdf'])assert(detail.includes(s),s);
assert(!detail.includes('mp.weixin.qq.com'), 'Luma is the actual source; do not fabricate a WeChat original');
assert(hub.includes(page));
assert(home.includes('class="hero-photo is-recap is-support-recap"'));
assert(home.split('id="activity-rail"')[1].match(/<article[\s\S]*?<\/article>/)[0].includes(page));
assert(archive.includes('14 场活动回顾'));
assert(archive.includes('data-filter="support"'));
assert.equal((archive.match(/data-category="support"/g)||[]).length,1);
const categories=[...archive.matchAll(/data-category="([^"]+)"/g)].map(x=>x[1]);
assert.equal(categories.length,14);
for(const [type,count] of Object.entries({keynote:7,workshop:4,member:1,founding:1,support:1}))assert.equal(categories.filter(x=>x===type).length,count,type);
const video=detail.match(/<video\b[^>]*>/)[0];
for(const s of ['width="1280"','height="720"','preload="none"','controlslist="nodownload"','playsinline','data-hls='])assert(video.includes(s),s);
assert(!video.includes('autoplay'));
const manifest=read(assets+'hls/replay.m3u8');
assert(manifest.includes('#EXT-X-ENDLIST'));
assert(manifest.includes('#EXT-X-INDEPENDENT-SEGMENTS'));
const durations=[...manifest.matchAll(/#EXTINF:([\d.]+)/g)].map(x=>+x[1]);
assert(Math.abs(durations.reduce((a,b)=>a+b,0)-3352)<.1);
const files=manifest.split('\n').filter(x=>x&&!x.startsWith('#'));
assert.equal(files.length,durations.length);
assert.equal(files.length,419);
for(const name of ['init.mp4',...files])assert(statSync(join(root,assets,'hls',name)).size>0);
for(const name of readdirSync(join(root,assets,'hls')))assert(statSync(join(root,assets,'hls',name)).size<10*1024*1024,'Unexpected large segment');
for(const file of ['feed.xml','llms.txt','llms-full.txt','sitemap.xml','sitemap-pages.xml','sitemap.txt'])assert(read(file).includes(page),file);
assert(statSync(join(root,assets+'poster.webp')).size>1000);
assert(statSync(join(root,assets+'nxt-build-sprint-report.pdf')).size>1000);
console.log('S01 checks passed: roles, dates, evidence, 14 records, source links, 419 complete HLS segments and lazy playback.');

